DEST_IP="[IP OF RPI5]"
INTERVAL=1  # seconds

send_loop() {
    local msg="$1"
    local port="$2"
    while true; do
        echo "Sending to port $port: $msg"
        echo -n "$msg"$'\r\n' | nc -u -w1 "$DEST_IP" "$port"
        sleep "$INTERVAL"
    done
}

send_array_loop() {
    local -n arr=$1  # use nameref for array
    local port="$2"
    while true; do
        for msg in "${arr[@]}"; do
            echo "Sending to port $port: $msg"
            echo -n "$msg"$'\r\n' | nc -u -w1 "$DEST_IP" "$port"
            sleep "$INTERVAL"
        done
    done
}

